export function resolveLang(prefLang, systemLocale) {
  let code = prefLang;
  if (!code || code === "auto") {
    const sys = String(systemLocale || "pt").toLowerCase();
    if (sys.startsWith("es")) code = "es";
    else if (sys.startsWith("en")) code = "en";
    else code = "pt";
  }
  return STRINGS[code] ? code : "pt";
}

export function tr(lang) {
  return STRINGS[lang] || STRINGS.pt;
}
